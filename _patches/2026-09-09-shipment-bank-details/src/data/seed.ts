function docs(
  spec: Partial<Record<ShipmentDocumentKey, Partial<ShipmentDocument>>>,
  required: ShipmentDocumentKey[],
): ShipmentDocument[] {
  const all: ShipmentDocumentKey[] = [
    "bill_of_lading",
    "commercial_invoice",
    "coo",
    "coo_customised",
    "packing_list",
    "fumigation",
    "phytosanitary",
    "health",
    "quality_certificate",
    "weight_certificate",
    "stuffing_report",
    "obl",
  ];
  return all.map((key) => ({
    key,
    state: required.includes(key) ? "not_issued" : "not_required",
    required: required.includes(key),
    comments: [],
    ...spec[key],
  }));
}

function charges(spec: Partial<Record<Charge["type"], Partial<Charge>>> = {}): Charge[] {
  const types: Charge["type"][] = ["local_invoice", "freight_invoice", "detention", "port_storage", "other"];
  // v2.0 §6.14 [PROPOSED]: "The charge default ceases to be No Charge. [AS-IS] an
  // untouched record is indistinguishable from one deliberately marked as having no
  // charge, so nothing can be chased." A charge therefore starts Awaited; only a
  // deliberate entry makes it Not applicable.
  return types.map((type) => ({
    type,
    status: "awaited" as const,
    ...spec[type],
  }));
}

function activities(
  keys: RegulatoryActivity["key"][],
  done: Partial<Record<RegulatoryActivity["key"], string>> = {},
  owners: Partial<Record<RegulatoryActivity["key"], RegulatoryActivity["owner"]>> = {},
): RegulatoryActivity[] {
  return keys.map((key) => ({
    key,
    applicable: true,
    completedDate: done[key],
    owner: owners[key] ?? "logistics",
  }));
}

function ms(entries: Record<string, Partial<Milestone>>): Milestone[] {
  return Object.entries(entries).map(([key, v]) => ({ key, state: "not_started", ...v }));
}

